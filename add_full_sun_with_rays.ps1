        $newLines += "                lineTo(12.5f, 10f)"
        $newLines += "                lineTo(11.5f, 10f)"
        $newLines += "                close()"
        $newLines += "                // Ray 6 (bottom-left)"
        $newLines += "                moveTo(9.5f, 7f)"
        $newLines += "                lineTo(8f, 8.5f)"
        $newLines += "                lineTo(9f, 9f)"
        $newLines += "                close()"
        $newLines += "                // Ray 7 (left)"
        $newLines += "                moveTo(8f, 5.5f)"
        $newLines += "                lineTo(6f, 5.5f)"
        $newLines += "                lineTo(6f, 4.5f)"
        $newLines += "                close()"
        $newLines += "                // Ray 8 (top-left)"
        $newLines += "                moveTo(9.5f, 3f)"
        $newLines += "                lineTo(8f, 1.5f)"
        $newLines += "                lineTo(9f, 1f)"
        $newLines += "                close()"
        $newLines += "            }"
        $newLines += "            // Full sun circle"
        $newLines += "            path("
        $newLines += "                fill = androidx.compose.ui.graphics.SolidColor(androidx.compose.ui.graphics.Color(0xFFFFB74D))"
        $newLines += "            ) {"
        $newLines += "                moveTo(15f, 5f)"
        $newLines += "                arcTo(3f, 3f, 0f, true, true, 9f, 5f)"
        $newLines += "                arcTo(3f, 3f, 0f, true, true, 15f, 5f)"
        $newLines += "                close()"
        $newLines += "            }"
        $newLines += "            // Mountain silhouette"
        $newLines += "            path("
        $newLines += "                fill = androidx.compose.ui.graphics.SolidColor(androidx.compose.ui.graphics.Color.Black)"
        $newLines += "            ) {"
        $newLines += "                moveTo(2f, 18f)"
        $newLines += "                lineTo(8f, 10f)"
        $newLines += "                lineTo(12f, 14f)"
        $newLines += "                lineTo(16f, 8f)"
        $newLines += "                lineTo(22f, 16f)"
        $newLines += "                lineTo(22f, 18f)"
        $newLines += "                close()"
        $newLines += "            }"
        $newLines += "        }.build()"
        $newLines += ""
        continue
    }
    
    # Stop skipping when we find Evening
    if ($skipUntilEvening -and $line -match 'val Evening') {
        $skipUntilEvening = $false
        $newLines += $line
        continue
    }
    
    # Skip lines while in TimeIcons reconstruction zone
    if ($skipUntilEvening) {
        continue
    }
    
    $newLines += $line
}

Set-Content $file $newLines

Write-Host "Done! Added full sun circles with 8 rays each"
